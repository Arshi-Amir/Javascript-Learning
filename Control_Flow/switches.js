let month = "Jan";

switch (month) {
    case "Dec":
        console.log("december");      
        break;

    case "march":
        console.log("march");  
        break;

    case "april":
        console.log("april");    
        break;

    case "jan":
        console.log("January");    
        break;

    default:
        console.log("Not Matched");       
        break;
}

// if break is not present it will print all logs except default